using System.Globalization;
using System.Reflection;
using System.Text;
using RecompRadar.Recompilation.Analysis;
using RecompRadar.Recompilation.IR;

namespace RecompRadar.Recompilation.Generation;

/// <summary>
/// Turns an analyzed program into a complete .NET project: one C# method per basic block, a dispatcher that follows the
/// recovered control flow, the guest memory image and the runtime support. Building that project yields a Windows program.
/// The generated code is translated CPU code that runs on the .NET JIT; it is not ahead-of-time compiled machine code.
/// </summary>
public static class CSharpGenerator
{
    public const string Namespace = "RecompRadar.Generated";

    public static GeneratedProject Generate(ProgramGraph graph, LoadedImage image, GenerationOptions options)
    {
        ArgumentNullException.ThrowIfNull(graph);
        ArgumentNullException.ThrowIfNull(image);
        ArgumentNullException.ThrowIfNull(options);

        var projectName = SanitizeName(options.ProjectName);
        if (!options.AllowIncomplete && graph.HasMissingCode)
        {
            var reasons = new List<string>();
            if (graph.UnsupportedInstructions.Count > 0)
            {
                reasons.Add($"{graph.UnsupportedInstructions.Count} unsupported instruction site(s), first: {graph.UnsupportedInstructions[0].Mnemonic} at 0x{graph.UnsupportedInstructions[0].Address:X8}");
            }

            if (graph.Truncated)
            {
                reasons.Add("the analysis hit its limit");
            }

            if (reasons.Count == 0)
            {
                reasons.Add("the analysis reported errors");
            }

            throw new GenerationException("The program cannot be recompiled completely: " + string.Join("; ", reasons) + ".");
        }

        var source = new StringBuilder();
        var irCount = EmitRecompiled(source, graph, options);
        var files = new SortedDictionary<string, byte[]>(StringComparer.Ordinal)
        {
            [$"{projectName}.csproj"] = Utf8(ProjectFile(projectName)),
            ["Directory.Build.props"] = Utf8("<Project />\n"),
            ["Directory.Build.targets"] = Utf8("<Project />\n"),
            ["Recompiled.cs"] = Utf8(source.ToString()),
            ["BuildInfo.cs"] = Utf8(BuildInfo(graph, options)),
            ["image.bin"] = ImageContainer.Write(image, options.Profile),
            ["GuestRuntime.cs"] = Utf8(Template("GuestRuntime.cs")),
            ["Program.cs"] = Utf8(Template("Program.cs")),
            ["IrSemantics.cs"] = Utf8(Template("IrSemantics.cs")),
            ["Ps2Runtime.cs"] = Utf8(Template("Ps2Runtime.cs")),
        };

        var stats = new GenerationStats(
            graph.Functions.Count,
            graph.Blocks.Count,
            graph.InstructionCount,
            irCount,
            graph.UnsupportedInstructions.Count,
            graph.IndirectJumps.Count,
            source.Length);
        return new GeneratedProject { ProjectName = projectName, ProjectFile = $"{projectName}.csproj", Files = files, Stats = stats };
    }

    public static string SanitizeName(string name)
    {
        var sb = new StringBuilder();
        foreach (var ch in name)
        {
            sb.Append(char.IsAsciiLetterOrDigit(ch) || ch is '_' or '-' ? ch : '_');
        }

        var result = sb.ToString().Trim('_', '-');
        if (result.Length == 0)
        {
            result = "Recompiled";
        }

        return char.IsAsciiDigit(result[0]) ? "P" + result : result;
    }

    private static byte[] Utf8(string text) => new UTF8Encoding(false).GetBytes(text.ReplaceLineEndings("\n"));

    private static string Template(string name)
    {
        var assembly = typeof(CSharpGenerator).Assembly;
        using var stream = assembly.GetManifestResourceStream($"Templates/{name}")
                           ?? throw new InvalidOperationException($"The embedded template '{name}' is missing.");
        using var reader = new StreamReader(stream, Encoding.UTF8);
        return reader.ReadToEnd();
    }

    private static string ProjectFile(string name) => $"""
        <Project Sdk="Microsoft.NET.Sdk">

          <!-- Generated by RecompRadar. The program is translated CPU code that runs on the .NET JIT and needs the .NET 10 runtime. -->
          <PropertyGroup>
            <OutputType>Exe</OutputType>
            <TargetFramework>net10.0</TargetFramework>
            <AssemblyName>{name}</AssemblyName>
            <RootNamespace>{Namespace}</RootNamespace>
            <ImplicitUsings>enable</ImplicitUsings>
            <Nullable>enable</Nullable>
            <LangVersion>latest</LangVersion>
            <Optimize>true</Optimize>
            <DebugType>none</DebugType>
            <Deterministic>true</Deterministic>
            <InvariantGlobalization>true</InvariantGlobalization>
            <TieredCompilation>false</TieredCompilation>
            <SatelliteResourceLanguages>en</SatelliteResourceLanguages>
            <GenerateDocumentationFile>false</GenerateDocumentationFile>
            <EnableNETAnalyzers>false</EnableNETAnalyzers>
            <TreatWarningsAsErrors>false</TreatWarningsAsErrors>
            <NoWarn>$(NoWarn);CS0219;CS0168;CS0162;CS8618</NoWarn>
          </PropertyGroup>

          <ItemGroup>
            <EmbeddedResource Include="image.bin" LogicalName="image.bin" />
          </ItemGroup>

        </Project>
        """.ReplaceLineEndings("\n") + "\n";

    private static string BuildInfo(ProgramGraph graph, GenerationOptions options)
    {
        var version = Literal(options.GeneratorVersion);
        var description = $"{options.SourceName} ({options.GuestArchitecture}), translated to C# by RecompRadar {options.GeneratorVersion}; " +
                          $"{graph.Functions.Count} functions, {graph.Blocks.Count} blocks, {graph.InstructionCount} guest instructions; " +
                          $"source SHA-256 {options.SourceSha256}. Runtime profile: {(options.Profile == RuntimeProfile.Ps2Ee ? "PlayStation 2 EE subset" : "RecompRadar test calls")}. Runs on the .NET JIT.";
        return $$"""
            // <auto-generated> RecompRadar. Do not edit. </auto-generated>
            namespace {{Namespace}};

            internal static class BuildInfo
            {
                public const string GeneratorVersion = {{version}};
                public const string SourceName = {{Literal(options.SourceName)}};
                public const string SourceSha256 = {{Literal(options.SourceSha256)}};
                public const string GuestArchitecture = {{Literal(options.GuestArchitecture)}};
                public const string Profile = {{Literal(options.Profile == RuntimeProfile.Ps2Ee ? "PlayStation 2 EE (kernel subset, serial output)" : "RecompRadar test calls")}};
                public const string Description = {{Literal(description)}};
            }

            """;
    }

    /// <summary>Emits Recompiled.cs and returns the number of IR instructions it contains.</summary>
    private static int EmitRecompiled(StringBuilder sb, ProgramGraph graph, GenerationOptions options)
    {
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"// Generated by RecompRadar {options.GeneratorVersion} from \"{options.SourceName}\" (SHA-256 {options.SourceSha256}).");
        sb.AppendLine($"// Guest architecture: {options.GuestArchitecture}. Do not edit; regenerate instead.");
        sb.AppendLine($"// {graph.Functions.Count} functions, {graph.Blocks.Count} basic blocks, {graph.InstructionCount} guest instructions.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("using RecompRadar.Semantics;");
        sb.AppendLine();
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();
        sb.AppendLine("internal static class Recompiled");
        sb.AppendLine("{");

        var ordered = graph.Blocks.Values.OrderBy(b => b.Start).ToList();

        sb.AppendLine("    /// <summary>Runs the program from <paramref name=\"pc\"/> until it exits, faults or reaches the instruction limit (all signalled by exceptions).</summary>");
        sb.AppendLine("    public static void Run(Cpu c, uint pc)");
        sb.AppendLine("    {");
        sb.AppendLine("        while (true)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (c.Executed >= c.Limit)");
        sb.AppendLine("            {");
        sb.AppendLine("                throw new StepLimitException(c.Executed);");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            switch (pc)");
        sb.AppendLine("            {");
        foreach (var block in ordered)
        {
            sb.AppendLine($"                case 0x{block.Start:X8}u: pc = B_{block.Start:X8}(c); break;");
        }

        sb.AppendLine("                default:");
        sb.AppendLine("                    if (c.TryKernelPc(pc, out var kernelPc))");
        sb.AppendLine("                    {");
        sb.AppendLine("                        pc = kernelPc;");
        sb.AppendLine("                        break;");
        sb.AppendLine("                    }");
        sb.AppendLine();
        sb.AppendLine("                    throw new GuestFaultException($\"Control flow reached 0x{pc:X8}, which static analysis did not find as code (an indirect jump or call target that was not recovered).\");");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        var functionOf = new Dictionary<ulong, FunctionInfo>();
        foreach (var function in graph.Functions.OrderByDescending(f => f.Entry))
        {
            foreach (var start in function.BlockStarts)
            {
                functionOf[start] = function; // the lowest entry wins because it is assigned last
            }
        }

        var irCount = 0;
        FunctionInfo? current = null;
        foreach (var block in ordered)
        {
            functionOf.TryGetValue(block.Start, out var function);
            if (!ReferenceEquals(function, current))
            {
                current = function;
                sb.AppendLine();
                sb.AppendLine(current is null
                    ? "    // ---- code not assigned to a function ----"
                    : $"    // ---- function {current.Name} (0x{current.Entry:X8}, {current.NameSource}) ----");
            }

            irCount += EmitBlock(sb, block);
        }

        sb.AppendLine("}");
        return irCount;
    }

    private sealed class RegisterUse
    {
        public SortedSet<int> Persistent { get; } = [];

        public SortedSet<int> Temporaries { get; } = [];

        public SortedSet<int> NeedLoad { get; } = [];

        public SortedSet<int> Written { get; } = [];

        private readonly HashSet<int> _definitelyWritten = [];

        public void Read(IrValue value)
        {
            if (value.IsImmediate || value.Value == 0)
            {
                return;
            }

            Touch((int)value.Value);
            var reg = (int)value.Value;
            if (IsPersistent(reg) && !_definitelyWritten.Contains(reg))
            {
                NeedLoad.Add(reg);
            }
        }

        public void ReadRegister(int reg) => Read(IrValue.Reg(reg));

        public void Write(int reg, bool conditional)
        {
            if (reg == 0)
            {
                return;
            }

            Touch(reg);
            if (IsPersistent(reg))
            {
                Written.Add(reg);
                if (conditional && !_definitelyWritten.Contains(reg))
                {
                    NeedLoad.Add(reg);
                }

                if (!conditional)
                {
                    _definitelyWritten.Add(reg);
                }
            }
        }

        private void Touch(int reg)
        {
            if (IsPersistent(reg))
            {
                Persistent.Add(reg);
            }
            else if (reg != Regs.Scratch)
            {
                Temporaries.Add(reg);
            }
        }

        public static bool IsPersistent(int reg) => reg is > 0 and < Regs.TempBase;
    }

    private static int EmitBlock(StringBuilder sb, CfgBlock cfg)
    {
        var block = cfg.Ir;
        var use = new RegisterUse();
        foreach (var i in block.Instructions)
        {
            if (IrInstruction.IsStore(i.Op))
            {
                use.Read(i.A);
                use.Read(i.B);
                continue;
            }

            use.Read(i.A);
            if (!IrInstruction.IsUnary(i.Op) && !IrInstruction.IsLoad(i.Op))
            {
                use.Read(i.B);
            }

            use.Write(i.Dest, conditional: i.Op is IrOp.MoveIfZero or IrOp.MoveIfNonZero);
        }

        switch (block.Terminator)
        {
            case IrBranch b:
                use.ReadRegister(b.ConditionRegister);
                break;
            case IrJumpRegister r:
                use.ReadRegister(r.Register);
                break;
        }

        sb.AppendLine();
        sb.AppendLine($"    // block 0x{block.StartAddress:X8}..0x{block.EndAddress:X8}, {block.GuestInstructionCount} guest instruction(s)");
        sb.AppendLine($"    private static uint B_{block.StartAddress:X8}(Cpu c)");
        sb.AppendLine("    {");
        foreach (var reg in use.Persistent)
        {
            sb.AppendLine(use.NeedLoad.Contains(reg) ? $"        uint {Regs.Name(reg)} = c.R[{reg}];" : $"        uint {Regs.Name(reg)} = 0;");
        }

        foreach (var reg in use.Temporaries)
        {
            sb.AppendLine($"        uint {Regs.Name(reg)} = 0;");
        }

        if (block.Instructions.Any(i => i.Dest == Regs.Scratch || i.Dest == 0))
        {
            sb.AppendLine("        uint scratch = 0;");
        }

        foreach (var i in block.Instructions)
        {
            sb.AppendLine($"        {Statement(i)} // {i.GuestAddress:X8}");
        }

        sb.AppendLine($"        c.Executed += {block.GuestInstructionCount};");
        foreach (var reg in use.Written)
        {
            sb.AppendLine($"        c.R[{reg}] = {Regs.Name(reg)};");
        }

        switch (block.Terminator)
        {
            case IrJump j:
                sb.AppendLine($"        return 0x{j.Target:X8}u;");
                break;
            case IrBranch b:
                sb.AppendLine($"        return {Regs.Name(b.ConditionRegister)} != 0u ? 0x{b.Taken:X8}u : 0x{b.NotTaken:X8}u;");
                break;
            case IrJumpRegister r:
                sb.AppendLine($"        return {Regs.Name(r.Register)};");
                break;
            case IrSyscall s:
                sb.AppendLine($"        return c.Syscall(0x{s.Continuation:X8}u);");
                break;
            case IrStop stop:
                sb.AppendLine($"        throw new ProgramStopException({Literal(stop.Reason)});");
                break;
            default:
                throw new GenerationException($"Unknown IR terminator {block.Terminator.GetType().Name} in block 0x{block.StartAddress:X8}.");
        }

        sb.AppendLine("    }");
        return block.Instructions.Count;
    }

    private static string Name(int reg) => reg == 0 ? "scratch" : Regs.Name(reg);

    private static string U(IrValue v) => v.IsImmediate ? $"0x{v.Value:X}u" : v.Value == 0 ? "0u" : Regs.Name((int)v.Value);

    private static string S(IrValue v) => $"unchecked((int){U(v)})";

    private static string Address(IrValue baseAddress, int offset) =>
        offset == 0 ? U(baseAddress) : $"unchecked({U(baseAddress)} + 0x{(uint)offset:X}u)";

    private static string Statement(IrInstruction i)
    {
        var d = Name(i.Dest);
        var a = U(i.A);
        var b = U(i.B);
        return i.Op switch
        {
            IrOp.Const or IrOp.Move => $"{d} = {a};",
            IrOp.Add => $"{d} = unchecked({a} + {b});",
            IrOp.Sub => $"{d} = unchecked({a} - {b});",
            IrOp.Mul => $"{d} = unchecked({a} * {b});",
            IrOp.And => $"{d} = {a} & {b};",
            IrOp.Or => $"{d} = {a} | {b};",
            IrOp.Xor => $"{d} = {a} ^ {b};",
            IrOp.Nor => $"{d} = ~({a} | {b});",
            IrOp.Shl => $"{d} = {a} << (int)({b} & 31u);",
            IrOp.Shr => $"{d} = {a} >> (int)({b} & 31u);",
            IrOp.Sar => $"{d} = unchecked((uint)({S(i.A)} >> (int)({b} & 31u)));",
            IrOp.SetEq => $"{d} = {a} == {b} ? 1u : 0u;",
            IrOp.SetNe => $"{d} = {a} != {b} ? 1u : 0u;",
            IrOp.SetLtSigned => $"{d} = {S(i.A)} < {S(i.B)} ? 1u : 0u;",
            IrOp.SetLtUnsigned => $"{d} = {a} < {b} ? 1u : 0u;",
            IrOp.LoadS8 => $"{d} = c.Mem.LoadS8({Address(i.A, i.Offset)});",
            IrOp.LoadU8 => $"{d} = c.Mem.LoadU8({Address(i.A, i.Offset)});",
            IrOp.LoadS16 => $"{d} = c.Mem.LoadS16({Address(i.A, i.Offset)});",
            IrOp.LoadU16 => $"{d} = c.Mem.LoadU16({Address(i.A, i.Offset)});",
            IrOp.Load32 => $"{d} = c.Mem.Load32({Address(i.A, i.Offset)});",
            IrOp.Store8 => $"c.Mem.Store8({Address(i.A, i.Offset)}, {b});",
            IrOp.Store16 => $"c.Mem.Store16({Address(i.A, i.Offset)}, {b});",
            IrOp.Store32 => $"c.Mem.Store32({Address(i.A, i.Offset)}, {b});",
            IrOp.MulHiS => $"{d} = Sem.MulHiS({a}, {b});",
            IrOp.MulHiU => $"{d} = Sem.MulHiU({a}, {b});",
            IrOp.DivS => $"{d} = Sem.DivS({a}, {b});",
            IrOp.RemS => $"{d} = Sem.RemS({a}, {b});",
            IrOp.DivU => $"{d} = Sem.DivU({a}, {b});",
            IrOp.RemU => $"{d} = Sem.RemU({a}, {b});",
            IrOp.MoveIfZero => $"if ({b} == 0u) {d} = {a};",
            IrOp.MoveIfNonZero => $"if ({b} != 0u) {d} = {a};",
            IrOp.FAdd => $"{d} = Sem.FAdd({a}, {b});",
            IrOp.FSub => $"{d} = Sem.FSub({a}, {b});",
            IrOp.FMul => $"{d} = Sem.FMul({a}, {b});",
            IrOp.FDiv => $"{d} = Sem.FDiv({a}, {b});",
            IrOp.FSqrt => $"{d} = Sem.FSqrt({a});",
            IrOp.FAbs => $"{d} = Sem.FAbs({a});",
            IrOp.FNeg => $"{d} = Sem.FNeg({a});",
            IrOp.CvtSW => $"{d} = Sem.CvtSW({a});",
            IrOp.CvtWS => $"{d} = Sem.CvtWS({a});",
            IrOp.TruncWS => $"{d} = Sem.TruncWS({a});",
            IrOp.FEq => $"{d} = Sem.FEq({a}, {b});",
            IrOp.FLt => $"{d} = Sem.FLt({a}, {b});",
            IrOp.FLe => $"{d} = Sem.FLe({a}, {b});",
            _ => throw new GenerationException($"The IR operation {i.Op} has no C# translation."),
        };
    }

    /// <summary>A C# string literal with every non-printable or non-ASCII character escaped.</summary>
    public static string Literal(string text)
    {
        var sb = new StringBuilder("\"");
        foreach (var ch in text)
        {
            switch (ch)
            {
                case '\\':
                    sb.Append("\\\\");
                    break;
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                case '\r':
                    sb.Append("\\r");
                    break;
                case '\t':
                    sb.Append("\\t");
                    break;
                default:
                    if (ch is < ' ' or > '~')
                    {
                        sb.Append("\\u").Append(((int)ch).ToString("X4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(ch);
                    }

                    break;
            }
        }

        return sb.Append('"').ToString();
    }

    public static string DefaultVersion =>
        typeof(CSharpGenerator).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion.Split('+')[0] ?? "3.0.0";
}
