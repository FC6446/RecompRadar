using System.Security.Cryptography;
using System.Text;
using RecompRadar.TestSupport;

// Regenerates the synthetic sample files in the samples/ folder.
// Usage: dotnet run --project tools/RecompRadar.SampleGenerator -- [output-directory]
// The output is fully deterministic, so re-running it produces byte-identical files.

var outputDirectory = Path.GetFullPath(args.Length > 0 ? args[0] : "samples");
Directory.CreateDirectory(outputDirectory);

var readme = new StringBuilder();
readme.AppendLine("# Sample files");
readme.AppendLine();
readme.AppendLine("All files in this folder are **synthetic**. They are generated by `tools/RecompRadar.SampleGenerator` from the");
readme.AppendLine("code in `tests/RecompRadar.TestSupport` and contain only ELF headers, tables, a few hand-written instructions and");
readme.AppendLine("made-up symbol names. They contain no code, data, firmware, keys or assets from any commercial product.");
readme.AppendLine();
readme.AppendLine("Files that mimic a console only copy *header characteristics* (CPU flags, addresses, naming patterns) so that the");
readme.AppendLine("analyzer's hints can be demonstrated. They are not real console executables and cannot run on one.");
readme.AppendLine();
readme.AppendLine("Open them in RecompRadar with drag and drop or **Open file**. Regenerate them with:");
readme.AppendLine();
readme.AppendLine("```");
readme.AppendLine("dotnet run --project tools/RecompRadar.SampleGenerator -- samples");
readme.AppendLine("```");
readme.AppendLine();
readme.AppendLine("| File | Size | SHA-256 | What it demonstrates |");
readme.AppendLine("| --- | ---: | --- | --- |");

foreach (var sample in SampleFiles.All())
{
    var path = Path.Combine(outputDirectory, sample.FileName);
    File.WriteAllBytes(path, sample.Bytes);
    var hash = Convert.ToHexString(SHA256.HashData(sample.Bytes)).ToLowerInvariant();
    readme.AppendLine($"| `{sample.FileName}` | {sample.Bytes.Length} B | `{hash[..16]}…` | {sample.Description} |");
    Console.WriteLine($"wrote {path} ({sample.Bytes.Length} bytes)");
}

File.WriteAllText(Path.Combine(outputDirectory, "README.md"), readme.ToString().Replace("\r\n", "\n"), new UTF8Encoding(false));
Console.WriteLine("done");
